-- ============================================================================
-- 0006 — Portal security hardening
--
-- The first portal build wrote with the public anon key. This migration moves
-- every portal read and write behind a Supabase Auth user whose
-- app_metadata.role is `ravsoft_admin`, removes anon access from client and
-- payment rows, and keeps only the outbound licence poll public.
--
-- Additive and idempotent. Run after 0005.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. Admin predicate
-- ---------------------------------------------------------------------------
create or replace function public.is_portal_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select
    coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'ravsoft_admin', false)
    or coalesce(auth.role() = 'service_role', false);
$$;

revoke all on function public.is_portal_admin() from public, anon;
grant execute on function public.is_portal_admin() to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 2. Replace the open demo policies
-- ---------------------------------------------------------------------------
drop policy if exists developer_installations_portal_all
  on public.developer_client_installations;
drop policy if exists developer_payments_portal_all
  on public.developer_license_payments;
drop policy if exists developer_update_runs_read
  on public.developer_update_runs;

create policy developer_installations_admin_all
  on public.developer_client_installations
  for all
  to authenticated
  using (public.is_portal_admin())
  with check (public.is_portal_admin());

create policy developer_payments_admin_all
  on public.developer_license_payments
  for all
  to authenticated
  using (public.is_portal_admin())
  with check (public.is_portal_admin());

create policy developer_update_runs_admin_read
  on public.developer_update_runs
  for select
  to authenticated
  using (public.is_portal_admin());

revoke all on public.developer_client_installations from anon;
revoke all on public.developer_license_payments from anon;
revoke all on public.developer_update_runs from anon;
revoke all on public.v_client_update_status from anon;

grant select, insert, update, delete
  on public.developer_client_installations to authenticated;
grant select, insert, update, delete
  on public.developer_license_payments to authenticated;
grant select on public.developer_update_runs to authenticated;
grant select on public.v_client_update_status to authenticated;

-- Views run with the caller's RLS, not the view owner's.
alter view public.v_client_update_status set (security_invoker = true);

-- ---------------------------------------------------------------------------
-- 3. Update RPCs: admin wrappers, service-role originals
-- ---------------------------------------------------------------------------
revoke execute on function public.request_client_update(text, text)
  from public, anon, authenticated;
revoke execute on function public.record_client_update_result(uuid, text, text)
  from public, anon, authenticated;

grant execute on function public.request_client_update(text, text) to service_role;
grant execute on function public.record_client_update_result(uuid, text, text)
  to service_role;

create or replace function public.portal_request_client_update(
  p_client_id text,
  p_to_version text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_portal_admin() then
    raise exception 'Not authorized.';
  end if;
  return public.request_client_update(p_client_id, p_to_version);
end;
$$;

revoke all on function public.portal_request_client_update(text, text)
  from public, anon;
grant execute on function public.portal_request_client_update(text, text)
  to authenticated, service_role;

